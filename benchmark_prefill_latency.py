def load_mistral_classes():
    """
    High-performance bypass import for MistralConfig and MistralForCausalLM.
    Pre-registers transformers.models in sys.modules to prevent the slow AST scan
    of all 300+ models in transformers/models/__init__.py.
    """
    try:
        import transformers

        if "transformers.models" not in sys.modules:
            models_pkg = types.ModuleType("transformers.models")
            models_dir = os.path.join(os.path.dirname(transformers.__file__), "models")
            models_pkg.__path__ = [models_dir]
            models_pkg.__file__ = os.path.join(models_dir, "__init__.py")
            models_pkg.__package__ = "transformers.models"
            sys.modules["transformers.models"] = models_pkg

        from transformers.models.mistral.configuration_mistral import MistralConfig
        from transformers.models.mistral.modeling_mistral import MistralForCausalLM

        return MistralConfig, MistralForCausalLM
    except Exception:
        try:
            from transformers import MistralConfig, MistralForCausalLM
            return MistralConfig, MistralForCausalLM
        except Exception:
            return None, None


