def get_torch_dtype(dtype_str: str) -> "torch.dtype":
    dtype_map = {
        "float16": torch.float16,
        "bfloat16": torch.bfloat16,
        "float32": torch.float32,
    }
    return dtype_map[dtype_str]


def compute_statistics(latencies_ms: List[float]) -> Dict[str, float]:
    """Computes median, mean, std, min, max, p25, p75, and p95."""
    sorted_latencies = sorted(latencies_ms)
    n = len(sorted_latencies)

    if n % 2 == 1:
        median = sorted_latencies[n // 2]
    else:
        median = (sorted_latencies[n // 2 - 1] + sorted_latencies[n // 2]) / 2.0

    mean = sum(sorted_latencies) / n
    variance = sum((x - mean) ** 2 for x in sorted_latencies) / (n - 1) if n > 1 else 0.0
    std_dev = math.sqrt(variance)

    def percentile(p: float) -> float:
        idx = int(round(p * (n - 1)))
        return sorted_latencies[idx]

    return {
        "median": median,
        "mean": mean,
        "std": std_dev,
        "min": sorted_latencies[0],
        "max": sorted_latencies[-1],
        "p25": percentile(0.25),
        "p75": percentile(0.75),
        "p95": percentile(0.95),
    }


def load_workloads_file(workloads_path: str) -> Dict[int, List[int]]:
    """
    Loads deterministic prompt token IDs from a workloads JSONL file generated by generate_workloads.py.
    Returns mapping: prefix_len -> token_ids.
    """
    path = Path(workloads_path)
    if not path.exists():
        raise FileNotFoundError(f"Workloads file not found: {workloads_path}")

    prefix_to_tokens: Dict[int, List[int]] = {}
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            prefix_len = row.get("prefix_len")
            token_ids = row.get("prompt_token_ids")
            if prefix_len is not None and token_ids is not None:
                if prefix_len not in prefix_to_tokens:
                    prefix_to_tokens[prefix_len] = token_ids

    return prefix_to_tokens


def create_or_load_mistral_model(
    MistralConfig_cls,
    MistralForCausalLM_cls,
    model_path: Optional[str],
    num_layers: int,
    hidden_size: int,
    intermediate_size: int,
    num_heads: int,
    num_kv_heads: int,
    vocab_size: int,
    max_position_embeddings: int,
    dtype_str: str,
    use_cache: bool,
    device: "torch.device",
    dtype: "torch.dtype",
):
    """
    Loads model either from a local directory (e.g. models/base downloaded by download_models.py)
    or initializes a randomly weighted Mistral model if model_path is None or dummy mode is used.
    """
    # 1. Check if user provided an existing model path or directory
    if model_path and Path(model_path).exists():
        print(f"[*] Loading base model from local path: {model_path}...", flush=True)
        try:
            from transformers import AutoConfig, AutoModelForCausalLM

            config = AutoConfig.from_pretrained(model_path)
            config.use_cache = use_cache
            model = AutoModelForCausalLM.from_pretrained(
                model_path,
                config=config,
                torch_dtype=dtype,
            ).to(device=device)
            model.eval()
            total_params = sum(p.numel() for p in model.parameters())
            param_size_gb = (sum(p.numel() * p.element_size() for p in model.parameters())) / (1024.0 ** 3)
            print(f"    - Loaded model from disk: {total_params:,} parameters ({param_size_gb:.2f} GB in {dtype_str})", flush=True)
            return model, config
        except Exception as e:
            print(f"    [!] Note: Could not load full checkpoint from {model_path} ({e}). Falling back to dummy architecture initialization.", flush=True)

    # 2. Initialize synthetic randomly weighted Mistral model (no network download)
    config = MistralConfig_cls(
        vocab_size=vocab_size,
        hidden_size=hidden_size,
        intermediate_size=intermediate_size,
        num_hidden_layers=num_layers,
        num_attention_heads=num_heads,
        num_key_value_heads=num_kv_heads,
        max_position_embeddings=max_position_embeddings,
        torch_dtype=dtype_str,
        use_cache=use_cache,
    )

    print(f"[*] Initializing randomly-weighted Mistral model on {device} ({dtype_str})...", flush=True)

    model = MistralForCausalLM_cls(config)
    model.to(device=device, dtype=dtype)
    model.eval()

    total_params = sum(p.numel() for p in model.parameters())
    param_size_gb = (sum(p.numel() * p.element_size() for p in model.parameters())) / (1024.0 ** 3)
    print(f"    - Model Parameters:   {total_params:,} ({param_size_gb:.2f} GB in {dtype_str})", flush=True)

    return model, config


def benchmark_context_length_cuda(
    model,
    input_ids: "torch.Tensor",
    device: "torch.device",
    iterations: int = 50,
    warmup: int = 10,
    use_cache: bool = True,
) -> Tuple[List[float], Dict[str, float]]:
    """Measures the forward prefill latency on CUDA using torch.cuda.Event."""
    # Warmup Phase
    for _ in range(warmup):
        with torch.no_grad():
            _ = model(input_ids=input_ids, use_cache=use_cache)
        torch.cuda.synchronize(device)
        torch.cuda.empty_cache()

    # Timed Iterations
    latencies_ms: List[float] = []
    start_event = torch.cuda.Event(enable_timing=True)
    end_event = torch.cuda.Event(enable_timing=True)

    torch.cuda.reset_peak_memory_stats(device)

    for _ in range(iterations):
        torch.cuda.synchronize(device)
        start_event.record()

        with torch.no_grad():
            _ = model(input_ids=input_ids, use_cache=use_cache)

        end_event.record()
        torch.cuda.synchronize(device)

        elapsed_ms = start_event.elapsed_time(end_event)
        latencies_ms.append(elapsed_ms)

        torch.cuda.empty_cache()

    peak_vram_mb = torch.cuda.max_memory_allocated(device) / (1024.0 * 1024.0)

    stats = compute_statistics(latencies_ms)
    stats["peak_vram_mb"] = peak_vram_mb
    return latencies_ms, stats


def benchmark_context_length_dryrun(
    model,
    input_ids: "torch.Tensor",
    iterations: int = 5,
    warmup: int = 2,
    use_cache: bool = True,
) -> Tuple[List[float], Dict[str, float]]:
    """CPU fallback benchmark for dry-run validation."""
    for _ in range(warmup):
        with torch.no_grad():
            _ = model(input_ids=input_ids, use_cache=use_cache)

    latencies_ms = []
    for _ in range(iterations):
        t0 = time.perf_counter_ns()
        with torch.no_grad():
            _ = model(input_ids=input_ids, use_cache=use_cache)
        t1 = time.perf_counter_ns()
        latencies_ms.append((t1 - t0) / 1e6)

    stats = compute_statistics(latencies_ms)
    stats["peak_vram_mb"] = 0.0
    return latencies_ms, stats


def measure_t_prefill(
    model: "torch.nn.Module",
    context_length: int,
    batch_size: int = 1,
    device: Optional[Union[str, "torch.device"]] = None,
    iterations: int = 50,
    warmup: int = 10,
    use_cache: bool = True,
    return_stats: bool = False,
) -> Union[float, Tuple[float, Dict[str, float]]]:
    """
    Callable benchmark function: measure_t_prefill(model, context_length).

    Measures the forward-pass prefill latency (Delta T_prefill) in milliseconds
    for a Large Language Model across a specified context length.

    Args:
        model: Initialized LLM model (e.g. MistralForCausalLM).
        context_length: Input sequence / context length L (e.g. 128, 256, 512, 1024, etc.).
        batch_size: Input batch size (default: 1).
        device: Target device (if None, inferred from model parameters).
        iterations: Number of timed iterations (default: 50).
        warmup: Number of untimed warmup iterations (default: 10).
        use_cache: Whether to generate and populate KV cache during prefill (default: True).
        return_stats: If True, returns (median_ms, stats_dict). Otherwise returns median_ms as float.

    Returns:
        float: Median forward-pass prefill latency Delta T_prefill in milliseconds.
    """
    if device is None:
        try:
            target_device = next(model.parameters()).device
        except (StopIteration, AttributeError):
            target_device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    elif isinstance(device, str):
        target_device = torch.device(device)
    else:
        target_device = device

    vocab_size = getattr(getattr(model, "config", None), "vocab_size", 32000)

    input_ids = torch.randint(
        low=0,
        high=vocab_size,
        size=(batch_size, context_length),
        device=target_device,
        dtype=torch.long,
    )

    if target_device.type == "cuda":
        torch.cuda.set_device(target_device)
        _, stats = benchmark_context_length_cuda(
            model=model,
            input_ids=input_ids,
            device=target_device,
            iterations=iterations,
            warmup=warmup,
            use_cache=use_cache,
        )
    else:
        _, stats = benchmark_context_length_dryrun(
            model=model,
            input_ids=input_ids,
            iterations=iterations,
            warmup=warmup,
            use_cache=use_cache,
        )

    median_ms = stats["median"]
    if return_stats:
        return median_ms, stats
    return median_ms


def export_paired_timings_for_analysis(
    prefill_results: List[Dict[str, float]],
    swap_csv_path: str,
    output_timings_path: str,
):
    """
    Exports a paired timings CSV matching the exact schema expected by analyze_results.py:
        prefix_len,lora_rank,prefill_saved_ms,swap_ms
    """
    swap_path = Path(swap_csv_path)
    if not swap_path.exists():
        print(f"[!] Warning: Swap CSV not found at {swap_csv_path}. Cannot generate paired timings.", flush=True)
        return

    # Read swap measurements
    swap_rows = []
    with open(swap_path, "r") as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Handle either 'rank' or 'lora_rank' and 'median' or 'swap_ms'
            rank = row.get("rank") or row.get("lora_rank")
            swap_ms = row.get("median") or row.get("swap_ms")
            if rank is not None and swap_ms is not None:
                swap_rows.append((int(rank), float(swap_ms)))

    if not swap_rows:
        print(f"[!] Warning: No valid rank/swap_ms data found in {swap_csv_path}.", flush=True)
        return

    # Cross join prefix lengths with lora ranks
    out_path = Path(output_timings_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    with open(out_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["prefix_len", "lora_rank", "prefill_saved_ms", "swap_ms"])
        for p_res in prefill_results:
            prefix_len = p_res["context_length"]
            prefill_saved_ms = p_res["median"]
            for lora_rank, swap_ms in swap_rows:
                writer.writerow([prefix_len, lora_rank, f"{prefill_saved_ms:.3f}", f"{swap_ms:.3f}"])

    print(f"[+] Exported paired timings to {output_timings_path} (Ready for analyze_results.py!)", flush=True)


